/**
 * 草稿工作区面板里文件树侧栏的分栏约束。
 *
 * 这个宿主是固定的 `w-[38%]` 窄列，owner 截图实测只有 265px —— 常量必须在这个宽度上
 * 仍然自洽：`min` 不能大过 `max` 在该宽度下能取到的值，否则两条约束互相打架。
 *
 * 定这些数只有一条硬规矩：**默认值必须落在可拖范围的中间，不能顶在任一端**。
 * 顶在上限时，往「把树拉宽」那个方向拖是死的 —— 而那正是用户看树太窄时的本能动作，
 * 拖不动就会判定「这条线还是不能拖」，owner 报的第一条缺陷原样复发。
 * （真机踩过：265px 列里像素初值 280px 被 `55%` 夹成 145，恰好等于上限 145.75，
 * 余量 0.55px，于是左拖零位移、右拖正常。）
 *
 * 所以初值在这里用**比例**而不是像素：像素初值在这么窄的列上必然被上限夹住 = 顶在端点。
 * 265px 下：树 146、正文 118，可拖范围 [120, 184]，两个方向各有 20+px 余量。
 *
 * 上限按比例给：宿主越窄树让得越多，spec 要求文件树
 * 「不能在紧凑的 workspace 面板中默认挤占正文宽度」。
 */

/** 再窄就只剩缩进，看不见文件名。 */
export const FILE_TREE_MIN_SIZE = '120px';

export const FILE_TREE_DRAFT_DEFAULT_SIZE = '55%';
export const FILE_TREE_DRAFT_MAX_SIZE = '72%';
export const FILE_TREE_DRAFT_HOST_MIN_SIZE = '80px';
