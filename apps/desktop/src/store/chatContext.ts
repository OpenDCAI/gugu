// @@@at-mention-draft (#4304/#951) - the @-mention targets a composer had selected, persisted per-chat
// alongside the draft TEXT so save/restore round-trips the mention→userId mapping. Without this, switching
// chats and back left the draft text "@name" but lost mentionTargets → send's toUserIds=[] → the mention
// degraded to plain text. Parallel map so the text-only draft API is untouched.
export type DraftMention = { userId: string; displayName: string }

// @@@draft-attachment (#1872) - a composer's QUEUED (not-yet-sent) attachments, persisted per-chat
// alongside the draft TEXT so save/restore round-trips them too. Without this the pending attachments
// were InputArea-local state that never learned about a chat switch: they leaked into the next chat's
// composer (composer stays mounted) or silently vanished (composer remounts) while the text — which IS
// in the store — restored correctly. We keep only the durable data (id/file/kind); the blob preview URL
// is a transient view concern regenerated by the composer on restore, never stored.
export type DraftAttachment = { id: string; file: File; kind: AttachmentKind }

