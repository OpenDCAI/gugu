import { z } from 'zod';
import { isPlanApprovalToolName, isQuestionToolName } from '../../session-record/sources/question-tools';
import type { PermissionWaitKind } from './session';
import { toolCallItemSchema, toolCallName, toolCallLabel } from './turns/tool-calls';
import { entityContentSchema } from './entity-content';

/** Structured approval context, including command and future subject variants. */
export const permissionSubjectSchema = entityContentSchema;
export type PermissionSubject = z.infer<typeof permissionSubjectSchema>;

export const acpPermissionOptionSchema = z.object({
  optionId: z.string(),
  /** Human-readable label from the ACP PermissionOption.name field. */
  name: z.string(),
  /**
   * ACP-defined kind hint. Standard values: 'allow_once', 'allow_always',
   * 'reject_once', 'reject_always'. May be extended by the agent.
   */
  kind: z.union([
    z.literal('allow_once'),
    z.literal('allow_always'),
    z.literal('reject_once'),
    z.literal('reject_always'),
    z.string(),
  ]),
});
export type AcpPermissionOption = z.infer<typeof acpPermissionOptionSchema>;

export const acpPermissionRequestSchema = z.object({
  /** Stable identifier generated by the owning SessionCell for this request. */
  requestId: z.string(),
  /** Display-ready snapshot of the typed tool call that triggered the request. */
  toolCall: toolCallItemSchema.optional(),
  title: z.string().optional(),
  description: z.string().nullable().optional(),
  subject: permissionSubjectSchema.nullable().optional(),
  _meta: z.record(z.string(), z.unknown()).nullable().optional(),
  options: z.array(acpPermissionOptionSchema),
});
export type AcpPermissionRequest = z.infer<typeof acpPermissionRequestSchema>;

export function permissionTitle(request: AcpPermissionRequest): string {
  return request.title ?? (request.toolCall ? toolCallLabel(request.toolCall) : '');
}

/** Approval text describes the requested operation without manufacturing a tool. */
export function permissionDescription(request: AcpPermissionRequest): string | undefined {
  const subject = request.subject;
  const parts = [request.description];
  if (subject?.type === 'command') {
    if (typeof subject.command === 'string') parts.push(subject.command);
    if (typeof subject.cwd === 'string') parts.push(subject.cwd);
  }
  return parts.filter(part => typeof part === 'string' && part.length).join('\n') || undefined;
}

export const permissionDecisionSchema = z.object({
  requestId: z.string(),
  optionId: z.string(),
});
export type PermissionDecision = z.infer<typeof permissionDecisionSchema>;

/** Runtime-advertised mode ids that mean the agent may act without asking. */
const DESTRUCTIVE_PERMISSION_MODE_PATTERN =
  /bypass|danger|full[-_]?access|yolo|unrestricted/i;

export function isDestructivePermissionMode(modeId: string): boolean {
  return DESTRUCTIVE_PERMISSION_MODE_PATTERN.test(modeId);
}

/**
 * 咕咕面向用户的四档权限,**按约束从严到松排列**。这是产品概念,不是任何一家 agent
 * 的原生档位 —— 各 agent 自报的档位由 classifyProviderPermissionMode() 归类到这四档。
 *
 * 为什么需要它:此前这里只有一个 `autoApprove: boolean`,它装不下多档 ——
 * 「不自动批准」既可能是只读、也可能是可改工作区,布尔一压就把两者混成一个值。
 * 后果是真的:applyConfiguredPermissionMode() 拿 autoApprove=false 去 find 第一个
 * 非破坏性档,codex 报 [:read-only, :workspace, :danger-full-access] 时选中的是
 * **只读** —— 用户以为选的是「改文件前问我」,拿到的是「根本不能改」。
 *
 * 为什么是四档而不是三档:`plan` 不是「只读」的别名,是另一件事 —— 只读是「能看不能动」,
 * 规划是「只产出方案,连动手的意图都不许有」。两家独立实现给出同一个阶梯:
 *   - Gemini CLI 源码里就按宽松度排好了序:PLAN < DEFAULT < AUTO_EDIT < YOLO
 *   - Claude Code 官方档位:plan / default(read-only) / acceptEdits / bypassPermissions
 *   - OpenCode 的 `plan` 是 primary agent,「Disallows all edit tools」
 * 没有 plan 的 harness(codex 只有 :read-only/:workspace/:danger-full-access)不声明这一档,
 * 界面上就不摆 —— 见 @@@permission-three-modes 的「不摆不存在的档」。
 */
export const GUGU_PERMISSION_MODES = ['plan', 'read-only', 'edit', 'full-access'] as const;
export type GuguPermissionMode = (typeof GUGU_PERMISSION_MODES)[number];

export function isGuguPermissionMode(value: unknown): value is GuguPermissionMode {
  return (
    typeof value === 'string' &&
    (GUGU_PERMISSION_MODES as readonly string[]).includes(value)
  );
}

const PLAN_PERMISSION_MODE_PATTERN = /^plan([-_ ]?mode)?$/i;
const READ_ONLY_PERMISSION_MODE_PATTERN = /read[-_]?only/i;

/**
 * 一个 harness 的原生档位 ↔ 咕咕三档的对应表,由**该 harness 自己声明**。
 *
 * 为什么必须显式声明、不能按 id 猜:claude 的 `default` 是**只读**档(官方原文
 * 「default (read-only)」),而同名的 `default` 在别家完全可能是可写档 —— 名字不携带语义。
 * claude 更有三个档都偏只读(`default` / `plan` / `dontAsk`),挑哪个当代表也只有它自己知道。
 *
 * 一档对多时,值填**代表** id(选中该档时就切到它);`aliases` 列出同属这一档的其它 id,
 * 用于反查 agent 当前档属于三档里的哪一档。
 */
export type ProviderPermissionModeMap = {
  [K in GuguPermissionMode]?: { id: string; aliases?: readonly string[]; legs?: readonly ('acp' | 'tui')[] };
};

/**
 * 把 agent 自报的原生档位 id 归类到咕咕三档。
 *
 * 有声明就查表 —— 那是唯一可靠的依据。没声明才退回按 id 猜:先判破坏性再判只读
 * (codex 的 `:danger-full-access` 两个词都沾,它是完全访问而不是只读),
 * 认不出来的算 edit（三档里的中位,既不放权也不至于让 agent 干不了活）。
 */
export function classifyProviderPermissionMode(
  modeId: string,
  map?: ProviderPermissionModeMap
): GuguPermissionMode {
  if (map) {
    for (const mode of GUGU_PERMISSION_MODES) {
      const entry = map[mode];
      if (!entry) continue;
      if (entry.id === modeId || entry.aliases?.includes(modeId)) return mode;
    }
  }
  if (isDestructivePermissionMode(modeId)) return 'full-access';
  if (PLAN_PERMISSION_MODE_PATTERN.test(modeId)) return 'plan';
  if (READ_ONLY_PERMISSION_MODE_PATTERN.test(modeId)) return 'read-only';
  return 'edit';
}

/**
 * 设置里那颗「默认自动批准」开关(一个布尔)对应的档位;存量记录里的 autoApprove 布尔已由
 * 0035_permission_mode_only 迁移按同一张表折成档位。
 *
 * `false` → `edit` 而不是 `read-only`:那个布尔的含义是「要不要自动批准」,不是「能不能写」,
 * 选 false 的用户要的是「改之前问我」。映射成只读会静默降权,agent 突然干不了活。
 */
export function permissionModeFromAutoApprove(autoApprove: boolean): GuguPermissionMode {
  return autoApprove ? 'full-access' : 'edit';
}

/**
 * 一条会话记录的有效档位 —— 界面、聊天面板腿、终端腿**同一个答案**。没有档位的记录(导入的)按编辑档,
 * 补出来的档照样显式传给 harness:「不加旗标」不是任何一档,是 harness 自己挑(claude 读用户的
 * defaultMode,再没有就是账号默认档,#7366)。
 */
export function resolveSessionPermissionMode(session: { permissionMode?: GuguPermissionMode }): GuguPermissionMode {
  return session.permissionMode ?? 'edit';
}

/** 给只认布尔的通道(TUI 的 autoApproveFlag、harness 的「全部放行」环境变量)。 */
export function autoApproveFromPermissionMode(mode: GuguPermissionMode): boolean {
  return mode === 'full-access';
}

/**
 * 「gugu 会不会替这个会话自动批准工具」—— 唯一一处判据。
 *
 * 推 auto-approve flag 的启动侧读它,派生 agent 状态的一侧也读它:一条通知到底是
 * 「真的阻塞在人」还是「轮内会被自动批准的事件」,两边必须由**同一条**表达式回答,
 * ❌ 各判一次(两份判据一旦分叉,一侧会在另一侧已经放行时仍把会话画成在等人)。
 *
 */
export function isAutoApproveIntent(intent: { permissionMode?: GuguPermissionMode }): boolean {
  return resolveSessionPermissionMode(intent) === 'full-access';
}

/**
 * 这个原生 id 能不能**代表**它被归到的那一档 —— 选档一侧的准入判据。
 *
 * 规则一句话:**该家声明过这一档,就只认它声明的那个 id;没声明这一档,才允许按名字猜填。**
 *
 * ⚠️ 与 `classifyProviderPermissionMode` 的分工:那个用于**显示** agent 当前处在哪一档,
 * 认不出来的猜成中位是对的(总得说出一个)。选档这一侧不能只靠猜 —— 声明表里已经为这一档
 * 指名了代表,别的 id 再被猜成同一档就是把用户放进一个产品从不提供的档。
 *
 * 三个真实的家把这条规则的三格各钉死一个,少了任何一格都会坏:
 *
 * · **claude**:四档全声明。它还报一个 `auto`(交给模型分类器判批准/拒绝),咕咕**故意不映射**
 *   ——那不是「能改多少」这条轴上的刻度而是「谁来决定」,会话页下拉也不摆它。但按名字猜会
 *   把它算成 `edit`,而 claude 把它排在档位表**第一个** ⇒ 不挡,用户选「编辑」时启动侧会
 *   选中 `auto`,选中的还是个下拉里不存在的选项。这一侧要求:**edit 已声明 ⇒ 只认 acceptEdits**。
 *
 * · **droid**:只声明有据的一档(`auto-high` = 完全访问,#4482 探针读数),
 *   `normal/spec/auto-low/auto-medium` 在两轴上怎么落没有读数、❌ 不猜,故意留空由启发式填
 *   (impl/droid/index.ts 抬头写死了这一条)。这一侧要求:**edit 没声明 ⇒ `normal` 必须能填**,
 *   否则用户选「编辑」时 droid 一档都挑不出来,ACP 会话根本起不来。
 *
 * · **qwen**:表是**完整**的(`modesExhaustive`),没声明的档就是这家没有。它报的 `auto-edit` 按名字
 *   会被猜成编辑,可它对任意路径的写入都放行、比编辑松(#6221 实测)。这一侧要求:**表完整 ⇒ 表里没点名的
 *   id 一档都代表不了**;droid 那一格「没声明才许猜」只给表不完整的家(#6953)。
 *
 * 没有声明表、表又不完整时恒 true:那种家整条路本来就退回按名字猜,这里不额外收紧。
 */
export function canRepresentPermissionMode(
  modeId: string,
  mode: GuguPermissionMode,
  map?: ProviderPermissionModeMap,
  exhaustive = false
): boolean {
  const entry = map?.[mode];
  if (!entry) return !exhaustive;
  return entry.id === modeId || (entry.aliases?.includes(modeId) ?? false);
}

/** 档位在阶梯上的位置 —— 数字越大越松(plan 0 < read-only 1 < edit 2 < full-access 3)。 */
function permissionModeRung(mode: GuguPermissionMode): number {
  return GUGU_PERMISSION_MODES.indexOf(mode);
}

/**
 * 用户选的是不是**阶梯顶端**(完全访问)。
 *
 * 这一格单独成判据,是因为它的后果是**可证的**而不是碰巧的:顶端之上没有更松的档,
 * 所以无论 agent 实际落在哪一档,都不可能给出比用户要的更大的权限 ⇒
 * **选了完全访问时,咕咕永不因为档位问题拒绝开会话**。
 *
 * owner 2026-09-05:「我不想失败不行吗」。而这条判据保证的正是"不失败"在安全上永远站得住 ——
 * ❌ 不是把 throw 一个个软化掉:选更严的档时,拿不到 ≤ 所选的档仍然响亮失败,
 * 因为那时"照样开"等于把用户放进一个比他选的更大的权限里(见 resolvePermissionModeFallback)。
 */
export function isTopPermissionRung(mode: GuguPermissionMode): boolean {
  return permissionModeRung(mode) === GUGU_PERMISSION_MODES.length - 1;
}

/**
 * 用户选的那一档这个 agent 没有时,落到哪一档 —— **不超过用户所选、且离它最近**的那一档。
 *
 * 不变量:**会话实际生效的档不得比用户所选的更松**。满足就把会话开起来(必要时降档),
 * 不满足才拒绝 —— owner 2026-09-05 定的原则:「用户既然选择了以 bypass 运行,
 * 我们就不该说启动不起来」。档位对不上不是拒绝开会话的理由,给出比用户要的**更大**的
 * 权限才是。
 *
 * 两个方向的代价不对称,所以规则不对称:
 * · 往严的方向落:agent 会多问几次(完全访问→编辑)或干得少(只读→规划),用户看得见 ——
 *   会话页的档位下拉显示的是**实际生效**那一档,不是他当初选的那一档。
 * · 往松的方向落:用户以为「改文件前问我」,agent 却已经动了手。❌ 这一侧一步都不许走,
 *   宁可响亮失败。
 *
 * 找不到任何一档 ≤ 所选(例:只报 `build` 的家 + 用户选了规划)时返回 undefined,
 * 由调用方响亮失败 —— 那正是「只剩比你要的更松的选项」这一格。
 */
export function resolvePermissionModeFallback(
  wanted: GuguPermissionMode,
  availableModeIds: readonly string[],
  map?: ProviderPermissionModeMap
): { modeId: string; mode: GuguPermissionMode } | undefined {
  const ceiling = permissionModeRung(wanted);
  let best: { modeId: string; mode: GuguPermissionMode } | undefined;
  for (const modeId of availableModeIds) {
    const mode = classifyProviderPermissionMode(modeId, map);
    // 该家为这一档指名过代表就只认那个 id(claude 的 `auto` 在这里被挡);没指名才许猜着填
    // (droid 的 `normal`)—— 见 canRepresentPermissionMode 抬头。
    if (!canRepresentPermissionMode(modeId, mode, map)) continue;
    const rung = permissionModeRung(mode);
    if (rung > ceiling) continue;
    // 同档并列时保留先出现的那个 —— 与精确匹配那条路的 find() 取法一致(claude 的
    // `default` / `dontAsk` 同归只读,声明表里的代表 id 排在前面)。
    if (best && permissionModeRung(best.mode) >= rung) continue;
    best = { modeId, mode };
  }
  return best;
}

/**
 * 这一家**实际能兑现**的档 —— composer 摆档与终端腿 argv 用的是同一个答案(#6221)。
 *
 * · 所选那档在档位表里 ⇒ 原样。
 * · 不在表里 ⇒ 沿阶梯往**严**的方向走,取第一个声明过的档(与 ACP runtime 的 `resolvePermissionModeFallback`
 *   同一个不变量:会话实际生效的档不得比所选的更松);一档都落不到 ⇒ `undefined`,由调用方决定怎么响亮。
 * · `full-access` 恒原样:它是阶梯顶端,实际落在哪一档都不可能比它更松;有些家的完全访问由会话包兑现、
 *   不在表里(opencode),❌ 因此把它降掉。
 * · 没声明档位表 ⇒ 原样(#6231 那 18 家逐家实测之前不替它们猜)。
 */
export function resolveDeclaredPermissionMode(
  wanted: GuguPermissionMode,
  modes: ProviderPermissionModeMap | undefined
): GuguPermissionMode | undefined {
  if (!modes || wanted === 'full-access' || modes[wanted]) return wanted;
  for (let rung = permissionModeRung(wanted) - 1; rung >= 0; rung -= 1) {
    const mode = GUGU_PERMISSION_MODES[rung]!;
    if (modes[mode]) return mode;
  }
  return undefined;
}

/** 这一家声明过的最严一档(阶梯最低处);没声明表时 `undefined`。 */
export function strictestDeclaredPermissionMode(
  modes: ProviderPermissionModeMap | undefined
): GuguPermissionMode | undefined {
  return modes ? GUGU_PERMISSION_MODES.find((mode) => modes[mode]) : undefined;
}

const REFUSAL_OPTION_KINDS: ReadonlySet<string> = new Set(['reject_once', 'reject_always']);
const ALLOW_OPTION_KINDS: ReadonlySet<string> = new Set(['allow_once', 'allow_always']);

/**
 * 这条权限请求在等人什么。完全访问档替不替人作答、状态投影成哪一种「需要你」,共用这一份判据:
 *  1. 提问 / 计划工具按名单认;
 *  2. 其余按选项结构认:带拒绝项或只有一个放行项 = 批准;其余(几个都拒绝不了的项)= 让人挑一个,是提问。
 * 不按标题文案猜;拿不准的方向是问人。
 */
export function permissionWaitKind(request: AcpPermissionRequest): PermissionWaitKind {
  const tool = request.toolCall ? toolCallName(request.toolCall) : '';
  if (isPlanApprovalToolName(tool)) return 'plan';
  if (isQuestionToolName(tool)) return 'question';
  const { options } = request;
  if (options.some((option) => REFUSAL_OPTION_KINDS.has(option.kind))) return 'approval';
  // 一个选项都没有的请求没有可答的:仍按批准走,完全访问档由 selectAutoApproveOption 照旧响亮报错。
  if (options.length <= 1 && options.every((option) => ALLOW_OPTION_KINDS.has(option.kind))) return 'approval';
  return 'question';
}
