import { z } from 'zod';
import type { TranscriptItem, TranscriptTurn } from './turns/turn';

/** Existing ACP scrollback cap, also the aggregate output budget for a stored turn. */
export const TERMINAL_OUTPUT_BYTE_LIMIT = 4 * 1024 * 1024;

export const terminalExitSchema = z.object({
  exitCode: z.number().int().nullable(),
  signal: z.string().nullable(),
});
export type TerminalExit = z.infer<typeof terminalExitSchema>;

/**
 * Shared presentation of an agent-owned display or a host-owned process.
 * Returned by AcpRuntime.getTerminals() so that a renderer reload
 * can hydrate the full terminal list from the main-process authority without
 * replaying any event stream.
 */
export const terminalStateSchema = z.object({
  /** Stable id generated by the runtime for this terminal. */
  terminalId: z.string(),
  /** Display-only terminals belong to the agent; host controls require a live handle. */
  owner: z.enum(['agent', 'host']),
  canKill: z.boolean(),
  _meta: z.record(z.string(), z.unknown()).optional(),
  /** The command that was executed. */
  command: z.string(),
  /** Arguments passed to the command. */
  args: z.array(z.string()),
  /** Working directory the command ran in. */
  cwd: z.string(),
  /**
   * All output captured so far (stdout + stderr merged), encoded as UTF-8.
   * Host output follows its process byte limit; display output follows the agent.
   * A stored turn separately bounds its referenced snapshots to the shared cap.
   */
  output: z.string(),
  /** True when output was truncated due to the outputByteLimit cap. */
  truncated: z.boolean(),
  /** Non-null once the command has exited. */
  exitStatus: terminalExitSchema.nullable(),
});
export type TerminalState = z.infer<typeof terminalStateSchema>;
export type TerminalSnapshot = TerminalState;

/** Provider ids are only unique within their connection and session. */
export function terminalEntityId(scope: string, terminalId: string): string {
  return JSON.stringify([scope, terminalId]);
}

/** Store only referenced presentation, through the existing whole-turn writer. */
export function withReferencedTerminals(turn: TranscriptTurn, available: readonly TerminalState[], limit = TERMINAL_OUTPUT_BYTE_LIMIT): TranscriptTurn {
  const ids = new Set<string>();
  const visit = (items: readonly TranscriptItem[]) => {
    for (const item of items) {
      if ('terminalId' in item && item.terminalId) ids.add(item.terminalId);
      if ('children' in item && item.children) visit(item.children);
    }
  };
  visit(turn.items);
  const byId = new Map([...(turn.terminals ?? []), ...available].map(terminal => [terminal.terminalId, terminal]));
  let remaining = limit;
  const terminals = [...ids].reverse().flatMap(id => {
    const terminal = byId.get(id);
    if (!terminal) return [];
    const bytes = new TextEncoder().encode(terminal.output);
    let start = Math.max(0, bytes.length - remaining);
    // Keep a UTF-8 boundary when discarding the oldest scrollback bytes.
    while (start < bytes.length && (bytes[start]! & 0xc0) === 0x80) start++;
    remaining -= bytes.length - start;
    return [{ ...terminal, canKill: false, output: start ? new TextDecoder().decode(bytes.subarray(start)) : terminal.output,
      truncated: terminal.truncated || start > 0 }];
  }).reverse();
  if ((!turn.terminals && terminals.length === 0) || JSON.stringify(turn.terminals) === JSON.stringify(terminals)) return turn;
  return { ...turn, terminals };
}
