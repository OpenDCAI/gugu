/**
 * 咕咕给 DeepSeek Harness 带进去的一个 Cordis 插件:把这条会话选的权限档写进 dsh 的会话。
 *
 * 为什么要它:dsh 自己在开着的会话里换档走 `/permission <档>`(Web 的权限下拉也是发这条命令),命令处理调
 * `ctx.permissionPresets.set(session, 档)` —— 但它的 ACP 面不带命令、也不带 modes。续接一条已有会话时,dsh
 * 沿用会话里钉下的那一档,环境变量与设置只管新会话(`dsh-permission-presets` README「Session defaults」)。
 * ⇒ 咕咕换档走 `reload-session`:带着新档重起进程、resume 同一条会话,这个插件在每一个 `agent/created`
 * (新建与续接时 dsh 都会给会话建 agent)上对 `agent.session` 调同一个 `set`,与 `/permission` 是同一条写入路。
 *
 * 为什么是 `agent/created` 而不是 `session/created`:0.2.2-rc.1 起会话在 `session/created` 发完之前不收任何事件
 * (「cannot append before session/created completes」),而 `set` 要追加一条 `permission/preset`;dsh 自己的预设
 * 服务也从 0.2.2 起改在 `agent/created`(prepend)上钉档。`agent/created` 在 0.2.1-rc.5 也有
 * (`dsh-agent` 经 `ctx.serial` 发,载荷 `{ agent }`),所以一个钩子覆盖两版,dsh 自己的钉档都先于它。
 *
 * 实测(gpu 0.2.1-rc.5 + mac1 0.2.2-rc.1):新建时 dsh 先钉它的默认档、插件再改;resume 时 dsh 先恢复钉下的那一档、
 * 插件再改;改完下一条命令就按新档跑(只读拒写 ↔ 完全访问放行)。
 *
 * 依赖 dsh 的内部名字(服务 `permissionPresets` 的 `current`/`set`,服务 `agents`,事件 `agent/created`)。服务缺了
 * 就在 `agent/created` 里抛:dsh 建 agent 失败,ACP 的 `session/new` / `session/resume` 失败,咕咕界面上报启动失败
 * —— ❌ 不悄悄按别的档跑。
 */
export const DSH_PERMISSION_PLUGIN_FILE = 'gugu-permission.mjs';

export const DSH_PERMISSION_PLUGIN_SOURCE = `// Generated by Gugu. Applies the session's permission preset through dsh's own write path.
export const name = 'gugu-permission'
export const inject = ['agents']
export function apply(ctx, config) {
  const preset = config && config.preset
  if (typeof preset !== 'string' || preset === '') throw new Error('gugu-permission: config.preset is required')
  const pin = (agent) => {
    const session = agent && agent.session
    if (!session) throw new Error('gugu-permission: agent/created carried no session')
    const service = ctx.get('permissionPresets')
    if (!service || typeof service.set !== 'function' || typeof service.current !== 'function') {
      throw new Error('gugu-permission: this DeepSeek Harness build has no permissionPresets.set; cannot apply preset ' + preset)
    }
    if (service.current(session) !== preset) service.set(session, preset)
    const effective = service.current(session)
    if (effective !== preset) throw new Error('gugu-permission: preset ' + preset + ' did not take effect (now ' + effective + ')')
  }
  ctx.on('agent/created', ({ agent }) => pin(agent))
  for (const agent of ctx.agents.list()) pin(agent)
}
`;
